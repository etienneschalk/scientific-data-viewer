#!/usr/bin/env python3
"""Generate the architecture diagrams in docs/architecture/ from the source code.

Writes, for each figure, a standalone SVG (``svg/<section>.svg``, light and dark
aware, rendered by GitHub), a single-page ``architecture.html`` with all of them,
and a ``README.md`` index. Module graphs are laid out by Graphviz from the import
statements; the flows are drawn by ``figures.py``.

    python scripts/architecture/generate.py           # needs Graphviz (`dot`)
    python scripts/architecture/generate.py --check   # consistency checks only

Before writing anything, and with ``--check``, the script verifies that every
module is placed in the diagrams, that every symbol the figures and text name
still exists in its file, and that the protocol notes match ``MessageTypes.ts``.
"""

from __future__ import annotations

import argparse
import re
import sys
from html import escape
from pathlib import Path
from xml.etree import ElementTree

import content
import figures
import graphs
from codebase import ROOT, CodebaseError, Message, facts, missing_symbols, protocol

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = ROOT / "docs" / "architecture"
GENERATED_NOTE = "Generated by scripts/architecture/generate.py from the source code: do not edit, run it again."
# Graphviz sizes are in points; scale them up so their text matches the hand-drawn figures
GV_SCALE = {
    "host-modules": 1.2,
    "webview-modules": 1.25,
    "interpreter": 1.15,
    "environment": 1.15,
}


def all_refs() -> dict[str, list[str]]:
    refs: dict[str, list[str]] = {}
    sources = [
        figures.PROCESSES_REFS,
        figures.OPEN_FILE_REFS,
        figures.PLOT_REFS,
        figures.PIPELINES_REFS,
        graphs.INTERPRETER_REFS,
        graphs.ENVIRONMENT_REFS,
    ]
    sources += [
        s.refs for s in content.sections(facts(), graphs.webview_host_imports())
    ]
    for source in sources:
        for path, symbols in source.items():
            refs.setdefault(path, []).extend(symbols)
    return refs


def problems() -> list[str]:
    found = graphs.coverage_problems() + [
        f"symbol not found: {m}" for m in missing_symbols(all_refs())
    ]
    requests, events = protocol()
    for kind, messages, notes in (
        ("request", requests, content.REQUEST_NOTES),
        ("event", events, content.EVENT_NOTES),
    ):
        names = {m.name for m in messages}
        found += [
            f"{kind} '{n}' of MessageTypes.ts has no entry in content.py"
            for n in sorted(names - notes.keys())
        ]
        found += [
            f"content.py describes {kind} '{n}', which MessageTypes.ts no longer has"
            for n in sorted(notes.keys() - names)
        ]
    return found


# ---------------------------------------------------------------- figures


def build_figures(f) -> dict[str, str]:
    """Section id -> SVG element (no embedded style)."""
    return {
        "processes": figures.processes(f),
        "host-modules": graphs.render(
            graphs.host_dot(),
            "Extension host modules as dependency layers, from extension.ts at the top to runProcess and src/shared at the bottom.",
        ),
        "webview-modules": graphs.render(
            graphs.webview_dot(),
            "Webview bundle modules: main imports the feature modules, which share bus, state, util and src/shared.",
        ),
        "open-file": figures.open_file(f),
        "plot": figures.plot(f),
        "interpreter": graphs.render(
            graphs.interpreter_dot(),
            "Interpreter selection: override setting, then the extension's own uv environment, then the Python "
            "extension's interpreter, then common paths; core packages decide readiness.",
        ),
        "environment": graphs.render(
            graphs.environment_dot(f),
            "Extension-owned environment at startup: restore an interrupted rebuild, reuse an up-to-date environment, "
            "or rebuild it with uv while keeping the previous one as a fallback.",
        ),
        "backend-packages": graphs.render(
            graphs.py_dot(),
            "Backend packages: cli calls info and plotting, which use opening and formats, which use environment; "
            "results, types and _bootstrap are imported everywhere.",
        ),
        "backend-pipelines": figures.pipelines(),
    }


def _display_width(section_id: str, svg: str) -> float:
    width = float(re.search(r'data-width="([\d.]+)"', svg).group(1))
    return width * GV_SCALE.get(section_id, 1.0)


def standalone_svg(section_id: str, svg: str, css: str) -> str:
    """SVG file with its own styles and background, for GitHub and image viewers."""
    width = _display_width(section_id, svg)
    view_box = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
    height = width * view_box[3] / view_box[2]
    if "xmlns=" not in svg[: svg.index(">")]:
        svg = svg.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
    svg = re.sub(
        r' data-width="[^"]+"',
        f' width="{width:.0f}" height="{height:.0f}"',
        svg,
        count=1,
    )
    head_end = svg.index(">") + 1
    background = f'<rect class="bg" x="{view_box[0]:g}" y="{view_box[1]:g}" width="100%" height="100%"/>'
    return f"<!-- {GENERATED_NOTE} -->\n{svg[:head_end]}<style><![CDATA[\n{css}]]></style>{background}{svg[head_end:]}\n"


def inline_svg(section_id: str, svg: str) -> str:
    width = _display_width(section_id, svg)
    return re.sub(
        r' data-width="[^"]+"', f' style="max-width:{width:.0f}px"', svg, count=1
    )


# ---------------------------------------------------------------- HTML page


def _inline_html(text: str) -> str:
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", escape(text, quote=False))


def _legend_html(items) -> str:
    chips = "".join(
        f'<span class="chip"><span class="{cls}"></span>{escape(text)}</span>'
        for cls, text in items
    )
    return f'<div class="keyrow">{chips}</div>'


def _protocol_html(requests: list[Message], events: list[Message]) -> str:
    rows = "".join(
        f"<tr><td>{m.name}</td><td><code>{escape(m.payload)}</code> → <code>{escape(m.result)}</code></td>"
        f"<td>{_inline_html(content.REQUEST_NOTES[m.name])}</td></tr>"
        for m in requests
    )
    event_rows = "".join(
        f'<tr><td class="ev">{m.name}</td><td><code>{escape(m.payload)}</code></td>'
        f"<td>{_inline_html(content.EVENT_NOTES[m.name])}</td></tr>"
        for m in events
    )
    return (
        '<div class="split"><div class="tablewrap"><table><thead><tr><th>Request</th><th>Payload → result</th>'
        f"<th>Host side</th></tr></thead><tbody>{rows}</tbody></table></div>"
        '<div class="tablewrap"><table><thead><tr><th>Event</th><th>Payload</th><th>Emitted when</th></tr></thead>'
        f"<tbody>{event_rows}</tbody></table></div></div>"
    )


def html_page(f, sections, svgs, requests, events) -> str:
    css = (HERE / "diagram.css").read_text(encoding="utf-8") + (
        HERE / "page.css"
    ).read_text(encoding="utf-8")
    toc = "".join(
        f'<a href="#{s.id}"><span>{i}</span>{escape(s.title)}</a>'
        for i, s in enumerate(sections, start=1)
    )
    body = []
    for i, s in enumerate(sections, start=1):
        parts = [
            f'<section id="{s.id}">',
            f'<h2><span class="n">{i}</span>{escape(s.title)}</h2>',
        ]
        parts.append(f"<p>{_inline_html(s.intro)}</p>")
        if s.legend:
            parts.append(_legend_html(s.legend))
        if s.figure:
            caption = (
                f"<figcaption>{_inline_html(s.caption)}</figcaption>"
                if s.caption
                else ""
            )
            parts.append(
                f'<figure><div class="scroll">{inline_svg(s.id, svgs[s.id])}</div>{caption}</figure>'
            )
        else:
            parts.append(_protocol_html(requests, events))
        if s.read:
            parts.append(
                f'<p class="files"><b>Read</b>{" · ".join(escape(r) for r in s.read)}</p>'
            )
        parts.append("</section>")
        body.append("\n".join(parts))
    sections_html = "\n\n".join(body)
    return f"""<!doctype html>
<!-- {GENERATED_NOTE} -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Scientific Data Viewer Architecture</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wght@600;700;800&family=IBM+Plex+Sans:wght@400;500;600&family=JetBrains+Mono:wght@400;600&display=swap">
<style>
{css}</style>
</head>
<body>
<div class="sheet">
<header>
<div class="eyebrow">eschalk0.scientific-data-viewer · v{f.version}</div>
<h1>{escape(content.TITLE)}</h1>
<p class="lede">{_inline_html(content.LEDE)}</p>
{_legend_html(content.LEGEND)}
<nav class="toc" aria-label="Diagrams">{toc}</nav>
</header>

{sections_html}

<footer>Generated by <code>scripts/architecture/generate.py</code> from the source of v{f.version}. Module graphs laid out by Graphviz from the import statements; the process overview, sequences and pipelines are drawn by <code>figures.py</code> from the code paths they name.</footer>
</div>
</body>
</html>
"""


# ---------------------------------------------------------------- Markdown index


def _md_table(header: list[str], rows: list[list[str]]) -> str:
    """Table aligned the way prettier formats it, so the pre-commit hook leaves it alone."""
    widths = [max(len(r[i]) for r in [header, *rows]) for i in range(len(header))]

    def line(cells: list[str]) -> str:
        padded = (c.ljust(w) for c, w in zip(cells, widths, strict=True))
        return "| " + " | ".join(padded) + " |"

    return "\n".join(
        [line(header), line(["-" * w for w in widths]), *(line(r) for r in rows)]
    )


def _md_code(type_text: str) -> str:
    return "`" + type_text.replace("|", "\\|") + "`"


def markdown_index(f, sections, requests, events) -> str:
    out = [
        f"<!-- {GENERATED_NOTE} -->",
        "",
        f"# {content.TITLE}",
        "",
        content.LEDE,
        "",
        f"Generated from the source of v{f.version}. The same diagrams are in one page in "
        "[architecture.html](architecture.html): open it in a browser (it adds hover tooltips with module paths).",
        "",
        "Colors: teal is the webview, blue the extension host, green the Python backend, yellow what lies outside "
        "the extension (VS Code, uv, data files, xarray), red a failure path. Solid arrows are calls, dashed arrows "
        "returns or responses.",
    ]
    for i, s in enumerate(sections, start=1):
        out += ["", f"## {i}. {s.title}", "", s.intro, ""]
        if s.figure:
            out.append(f"![{s.title}](svg/{s.id}.svg)")
            if s.caption:
                out += ["", f"_{s.caption}_"]
        else:
            out.append(
                _md_table(
                    ["Request", "Payload", "Result", "Host side"],
                    [
                        [
                            m.name,
                            _md_code(m.payload),
                            _md_code(m.result),
                            content.REQUEST_NOTES[m.name],
                        ]
                        for m in requests
                    ],
                )
            )
            out += [
                "",
                _md_table(
                    ["Event", "Payload", "Emitted when"],
                    [
                        [m.name, _md_code(m.payload), content.EVENT_NOTES[m.name]]
                        for m in events
                    ],
                ),
            ]
        if s.read:
            out += ["", "Read: " + " · ".join(f"`{r}`" for r in s.read)]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- main


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help="output folder (default: docs/architecture)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="only check that the diagrams still match the code",
    )
    args = parser.parse_args(argv)

    try:
        found = problems()
    except CodebaseError as exc:
        found = [str(exc)]
    if found:
        print(
            "The architecture diagrams no longer match the code (see scripts/architecture/):",
            file=sys.stderr,
        )
        for problem in found:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    if args.check:
        print(
            "Architecture diagrams: every module is placed and every referenced symbol exists."
        )
        return 0
    if not graphs.dot_available():
        print(
            "Graphviz is required: install it (apt install graphviz, brew install graphviz, choco install graphviz).",
            file=sys.stderr,
        )
        return 1

    f = facts()
    sections = content.sections(f, graphs.webview_host_imports())
    requests, events = protocol()
    svgs = build_figures(f)
    css = (HERE / "diagram.css").read_text(encoding="utf-8")

    svg_dir = args.out / "svg"
    svg_dir.mkdir(parents=True, exist_ok=True)
    for section_id, svg in svgs.items():
        document = standalone_svg(section_id, svg, css)
        # Browsers refuse to show an <img> whose SVG is not well-formed XML
        ElementTree.fromstring(document)
        (svg_dir / f"{section_id}.svg").write_text(document, encoding="utf-8")
    (args.out / "architecture.html").write_text(
        html_page(f, sections, svgs, requests, events), encoding="utf-8"
    )
    (args.out / "README.md").write_text(
        markdown_index(f, sections, requests, events), encoding="utf-8"
    )
    print(
        f"Wrote {len(svgs)} SVG figures, architecture.html and README.md to {args.out}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
